"""Write BENCHMARK.md from measured runs. Every number in the file comes from this script.

Usage: python scripts/benchmark.py [--ames]
Synthetic runs are offline. --ames adds the real Ames split (downloads to the user cache).
"""

from __future__ import annotations

import argparse
import platform
import statistics
import time
from pathlib import Path

import numpy as np
import pandas as pd

from home_value_model import __version__
from home_value_model.batch import value_table
from home_value_model.data import load_ames, synthetic, time_split
from home_value_model.model import AVM
from home_value_model.report import evaluate

ROOT = Path(__file__).resolve().parent.parent
SEEDS = [0, 1, 2, 3, 4]


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ames", action="store_true")
    args = ap.parse_args()
    lines = [
        "# Benchmark",
        "",
        f"Generated by `scripts/benchmark.py` (home-value-model {__version__}). "
        "Nothing here is typed by hand.",
        f"Machine: {platform.system()} {platform.machine()}, Python {platform.python_version()}.",
        "",
        "## Synthetic data, 5 seeds",
        "",
        "1,500 seeded fake homes per seed, train on sales before 2009, test on 2009 and later. "
        "The price formula has noise with a 0.09 log standard deviation, so there is a hard "
        "floor on how well any model can do.",
        "",
        "| Seed | Train | Test | Hedonic MdAPE | GBM MdAPE | GBM PPE10 | High-band PPE10 "
        "| Low-band PPE10 | Fit seconds |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    fit_times: list[float] = []
    gbm_ppe: list[float] = []
    last: tuple[AVM, pd.DataFrame] | None = None
    for seed in SEEDS:
        df = synthetic(1500, seed)
        train, test = time_split(df)
        t0 = time.perf_counter()
        model = AVM(seed).fit(train)
        dt = time.perf_counter() - t0
        rep = evaluate(model, test, train)
        bands = rep["confidence_bands"]
        fit_times.append(dt)
        gbm_ppe.append(rep["gbm"]["ppe10"])
        lines.append(
            f"| {seed} | {len(train)} | {len(test)} | {pct(rep['hedonic']['mdape'])} "
            f"| {pct(rep['gbm']['mdape'])} | {pct(rep['gbm']['ppe10'])} "
            f"| {pct(bands['high']['ppe10'])} | {pct(bands['low']['ppe10'])} | {dt:.1f} |"
        )
        last = (model, test)
    lines += [
        "",
        f"Mean GBM PPE10 across seeds: {pct(statistics.mean(gbm_ppe))}. "
        f"Mean fit time: {statistics.mean(fit_times):.1f} s.",
    ]
    if last is not None:
        model, test = last
        big = pd.concat([test] * 20, ignore_index=True)
        t0 = time.perf_counter()
        res, _ = value_table(model, big)
        dt = time.perf_counter() - t0
        lines += [
            "",
            "## Batch speed",
            "",
            f"`value_table` on {len(big):,} rows (validation, both models, confidence): "
            f"{dt:.2f} s, {len(big) / dt:,.0f} rows per second. Rows returned: {len(res):,}.",
        ]
    if args.ames:
        df = load_ames()
        train, test = time_split(df)
        model = AVM(0).fit(train)
        rep = evaluate(model, test, train)
        lines += [
            "",
            "## Ames, Iowa (real data, downloaded at run time)",
            "",
            f"{len(train)} train sales (2006 to 2008), {len(test)} test sales (2009 to 2010).",
            "",
            "| Model | MdAPE | PPE10 | FSD | COD |",
            "|---|---|---|---|---|",
        ]
        for key, label in [
            ("baseline_ppsf", "Neighborhood $/sq ft rule"),
            ("hedonic", "Hedonic"),
            ("gbm", "Gradient boosting"),
            ("blend", "Average of the two"),
        ]:
            m = rep[key]
            lines.append(
                f"| {label} | {pct(m['mdape'])} | {pct(m['ppe10'])} | {m['fsd']:.3f} "
                f"| {m['cod']:.1f} |"
            )
        lines += ["", f"80% range coverage on test: {pct(rep['range_coverage'])}."]
    _ = np  # keep numpy import explicit for reproducibility notes
    (ROOT / "BENCHMARK.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote BENCHMARK.md")


if __name__ == "__main__":
    main()
